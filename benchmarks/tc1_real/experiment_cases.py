"""Independent TC1-Real task variants and critical-context references.

These requirements are part of the experiment specification, not generated by
the GeoTask policy under test.  This prevents RG from defining its own grading
rubric after seeing available context candidates.

The cases define context-preparation requirements only. They do not define or
certify real flight feasibility.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Mapping

from geotask_core.task_context import ContextRequirement, TaskFrame


PHX_EXPERIMENT_BBOX = (-112.10, 33.40, -112.00, 33.50)
EXPERIMENT_SPATIAL_SCOPE = "tc1-real-phx-bbox-v0.1"
EXPERIMENT_SUBJECT = "fictional-small-uas"


@dataclass(frozen=True)
class ReferenceRequirement:
    requirement: ContextRequirement
    basis: str
    grading_state: str = "accepted"
    notes: str = ""

    def __post_init__(self) -> None:
        if self.grading_state not in {"accepted", "disputed", "excluded"}:
            raise ValueError(
                "grading_state must be accepted, disputed, or excluded"
            )


@dataclass(frozen=True)
class TC1RealCase:
    case_id: str
    purpose: str
    task: TaskFrame
    reference_requirements: tuple[ReferenceRequirement, ...]
    expected_stress: str
    metadata: Mapping[str, object]

    @property
    def headline_requirement_ids(self) -> tuple[str, ...]:
        return tuple(
            item.requirement.requirement_id
            for item in self.reference_requirements
            if item.grading_state == "accepted" and item.requirement.critical
        )


def _task(case_id: str) -> TaskFrame:
    # The exact recorded weather run/valid time belongs to each acquired fixture.
    # This task scope names the experiment window contract rather than inventing
    # a live forecast timestamp before acquisition.
    return TaskFrame(
        task_id=case_id,
        goal="Prepare bounded public-source context for a fictional UAS mission",
        subject_refs=(EXPERIMENT_SUBJECT,),
        spatial_scope=EXPERIMENT_SPATIAL_SCOPE,
        temporal_scope="recorded-experiment-window",
        outputs=("mission_context",),
    )


def _base_requirements() -> tuple[ReferenceRequirement, ...]:
    return (
        ReferenceRequirement(
            requirement=ContextRequirement(
                requirement_id="airspace_guidance",
                what="UAS Facility Map context intersecting the experiment area",
                reason=(
                    "The experiment explicitly tests controlled-airspace planning "
                    "context; UASFM is informational and is not authorization."
                ),
                critical=True,
                spatial_scope=EXPERIMENT_SPATIAL_SCOPE,
            ),
            basis="TC1-Real experiment specification + FAA UASFM source semantics",
        ),
        ReferenceRequirement(
            requirement=ContextRequirement(
                requirement_id="obstacle_context",
                what="DDOF obstacle records spatially selected for the experiment area",
                reason=(
                    "The experiment measures broad obstacle acquisition versus "
                    "task-bounded local context selection."
                ),
                critical=True,
                spatial_scope=EXPERIMENT_SPATIAL_SCOPE,
            ),
            basis="TC1-Real experiment specification + FAA DDOF source semantics",
            notes=(
                "DDOF is not exhaustive; satisfying this requirement means the "
                "declared DDOF context was prepared, not that all obstacles are known."
            ),
        ),
        ReferenceRequirement(
            requirement=ContextRequirement(
                requirement_id="weather_wind",
                what="recorded HRRR 10 m wind components for the experiment region/time",
                reason="Wind is a declared weather input for the experiment context.",
                critical=True,
                spatial_scope=EXPERIMENT_SPATIAL_SCOPE,
                temporal_scope="recorded-experiment-window",
                max_spatial_resolution=3000.0,
                spatial_resolution_unit="meter",
                max_temporal_resolution_seconds=3600.0,
            ),
            basis="TC1-Real experiment specification + NOAA HRRR source semantics",
        ),
        ReferenceRequirement(
            requirement=ContextRequirement(
                requirement_id="weather_visibility",
                what="recorded HRRR visibility context for the experiment region/time",
                reason="Visibility is a declared weather input for the experiment context.",
                critical=True,
                spatial_scope=EXPERIMENT_SPATIAL_SCOPE,
                temporal_scope="recorded-experiment-window",
                max_spatial_resolution=3000.0,
                spatial_resolution_unit="meter",
                max_temporal_resolution_seconds=3600.0,
            ),
            basis="TC1-Real experiment specification + NOAA HRRR source semantics",
        ),
    )


def tc1_real_cases() -> tuple[TC1RealCase, ...]:
    requirements = _base_requirements()
    return (
        TC1RealCase(
            case_id="M1-controlled-airspace-context",
            purpose="Measure bounded airspace/weather acquisition plus local obstacle selection.",
            task=_task("M1-controlled-airspace-context"),
            reference_requirements=requirements,
            expected_stress="provider composition",
            metadata={
                "bbox": PHX_EXPERIMENT_BBOX,
                "activation_condition": (
                    "Recorded UASFM fixture must contain at least one feature "
                    "intersecting the experiment bbox; otherwise select another "
                    "documented bbox before grading M1."
                ),
            },
        ),
        TC1RealCase(
            case_id="M2-local-obstacle-selection",
            purpose="Measure broad DDOF acquisition versus task-bounded obstacle context.",
            task=_task("M2-local-obstacle-selection"),
            reference_requirements=requirements,
            expected_stress="broad provider + local selection",
            metadata={"bbox": PHX_EXPERIMENT_BBOX},
        ),
        TC1RealCase(
            case_id="M3-weather-temporal-mismatch",
            purpose="Verify that an HRRR artifact from the wrong recorded valid time remains a gap.",
            task=_task("M3-weather-temporal-mismatch"),
            reference_requirements=requirements,
            expected_stress="temporal applicability",
            metadata={
                "bbox": PHX_EXPERIMENT_BBOX,
                "required_perturbation": "weather valid time outside task window",
            },
        ),
        TC1RealCase(
            case_id="M4-unnecessary-weather-breadth",
            purpose=(
                "Compare task-specific HRRR variables/levels/region against a "
                "broader retrieval without changing the frozen critical requirements."
            ),
            task=_task("M4-unnecessary-weather-breadth"),
            reference_requirements=requirements,
            expected_stress="unnecessary context breadth",
            metadata={
                "bbox": PHX_EXPERIMENT_BBOX,
                "required_weather_variables": ("UGRD", "VGRD", "VIS"),
                "required_weather_levels": ("10_m_above_ground", "surface"),
            },
        ),
    )


def get_tc1_real_case(case_id: str) -> TC1RealCase:
    for case in tc1_real_cases():
        if case.case_id == case_id:
            return case
    raise KeyError(f"unknown TC1-Real case: {case_id}")
